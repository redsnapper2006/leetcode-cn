use std::collections::HashMap;

impl Solution {
  pub fn find_max_path_score(edges: Vec<Vec<i32>>, online: Vec<bool>, k: i64) -> i32 {
    let mut m: HashMap<usize, Vec<(usize, i64)>> = HashMap::new();
    let mut start: i64 = i64::MAX;
    let mut end: i64 = 0;
    edges.iter().for_each(|e| {
      if !online[e[0] as usize] || !online[e[1] as usize] {
        return;
      }
      m.entry(e[0] as usize).or_insert(vec![]).push((e[1] as usize, e[2] as i64));
      start = start.min(e[2] as i64);
      end = end.max(e[2] as i64);
    });

    fn dfs(
      node: usize, count: usize, mid: i64, m: &HashMap<usize, Vec<(usize, i64)>>,
      cache: &mut Vec<i64>,
    ) -> i64 {
      if node == count - 1 {
        return 0;
      }
      if cache[node] != -1 {
        return cache[node];
      }

      let mut ret: i64 = i64::MAX / 2;
      if m.contains_key(&node) {
        for nxt in m.get(&node).unwrap() {
          if nxt.1 >= mid {
            ret = ret.min(dfs(nxt.0, count, mid, m, cache) + nxt.1);
          }
        }
      }
      cache[node] = ret;
      ret
    }

    let mut cache: Vec<i64> = vec![-1; online.len()];
    if dfs(0, online.len(), start, &m, &mut cache) > k {
      return -1;
    }
    while start <= end {
      let mid = start + (end - start) / 2;
      cache = vec![-1; online.len()];
      if dfs(0, online.len(), mid, &m, &mut cache) <= k {
        start = mid + 1;
      } else {
        end = mid - 1;
      }
    }

    start as i32 - 1
  }
}

